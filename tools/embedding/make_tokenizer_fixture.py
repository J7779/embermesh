#!/usr/bin/env python3
"""Writes core/tests/data/guides/tokenizer_parity.tsv: sentences with the token ids the reference
tokenizer (Hugging Face `tokenizers`, the model's own tokenizer.json) produces for them, with
[UNK] removed exactly as Model2Vec does. The C++ test (core/tests/guides/embed_test.cpp) checks
that guides/embed.cpp produces the same ids, so parity is proven without Python.

Sentences: a deterministic sample of sentences from guides/content (each line records the guide
it came from; the guide file carries the text's source, licence and attribution), plus
hand-written Unicode edge cases.

Usage: make_tokenizer_fixture.py --tokenizer <tokenizer.json> --content guides/content
                                 --out core/tests/data/guides/tokenizer_parity.tsv [--count 450]
"""
import argparse
import hashlib
import os
import re

EDGE_CASES = [
    "UV-5R handheld on 146.520 MHz, CTCSS 100.0 Hz; don't key up!",
    "Café, naïve, façade, Ångström, Øresund, Straße, Œuvre, Æsir, þorn",
    "ΑΒΓ Δέλτα ΣΊΣΥΦΟΣ — κόσμος; Привет, МИР! Ёлка",
    "日本語のテキスト、中文字符和한국어 문장 mixed with English",
    "fullwidth ＵＶ－５Ｒ ＡＢＣ １２３ and ﬁ ligature ﬂow",
    "combining: e\u0301 a\u0300 n\u0303 o\u0308 and zero\u200bwidth\u200d joiner\u00ad soft hyphen",
    "nbsp\u00a0here, thin\u2009space, ideographic\u3000space, tab\tand newline\nend",
    "emoji 🔥🚑💧 and symbols © ® ™ ° ± × ÷ § ¶ € £ ¥ ‰ ← → ↑ ↓",
    "quotes “double” ‘single’ «guillemets» „low“ and dashes – — ‐ ‑",
    "[CLS] literal [SEP] tokens [MASK] inside [UNK] text [PAD] and [cls] lower",
    "x" * 99 + " " + "y" * 100 + " " + "z" * 101,
    "supercalifragilisticexpialidocious antidisestablishmentarianism pneumonoultramicroscopic",
    "İstanbul ıiİI Ǆ ǅ ǆ ǈ Ⅻ ⅻ ① ⑳ ½ ¾ ² ³",
    "ॐ नमस्ते देवनागरी ক্ষ ো ৌ தமிழ் ொ",
    "control\x01chars\x7fhere and \ufffd replacement and \ufeff bom",
    "hello...world!!! a/b\\c (d) [e] {f} <g> @h #i $j %k ^l &m *n _o +p =q |r ~s `t",
    "1,000 3.14159 1e-5 10:30 2026-11-14 50% +/- 9-line N0CALL-1",
    "",
    "   ",
    "A",
]


def sentences(content):
    out = []
    for root, dirs, files in os.walk(content):
        dirs[:] = sorted(d for d in dirs if not d.startswith(("_", ".")))
        for f in sorted(files):
            if not f.endswith(".md") or f.startswith(("_", ".")):
                continue
            path = os.path.join(root, f)
            gid = os.path.relpath(path, content)[:-3].replace(os.sep, "/")
            text = open(path, encoding="utf-8").read()
            body = text.split("\n---\n", 1)[1] if text.startswith("---\n") and "\n---\n" in text else text
            for para in re.split(r"\n\s*\n", body):
                para = " ".join(para.split())
                for s in re.split(r"(?<=[.!?])\s+", para):
                    if 30 <= len(s) <= 220 and "\t" not in s:
                        out.append((gid, s))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokenizer", required=True)
    ap.add_argument("--content", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--count", type=int, default=450)
    ap.add_argument("--exclude", action="append", default=[], help="skip guides whose id contains this text")
    a = ap.parse_args()
    from tokenizers import Tokenizer

    tok = Tokenizer.from_file(a.tokenizer)
    unk = tok.token_to_id("[UNK]")
    pool = [x for x in sentences(a.content) if not any(e in x[0] for e in a.exclude)]
    # Deterministic sample, biased towards non-ASCII sentences (they exercise the tables).
    key = lambda x: hashlib.sha256((x[0] + "\0" + x[1]).encode()).hexdigest()
    pool.sort(key=key)
    non_ascii = [x for x in pool if any(ord(c) > 127 for c in x[1])][: a.count // 4]
    ascii_ = [x for x in pool if x not in non_ascii][: a.count - len(non_ascii)]
    rows = [("edge", s) for s in EDGE_CASES] + sorted(non_ascii + ascii_, key=key)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Tokenizer parity fixture, generated by tools/embedding/make_tokenizer_fixture.py; do not edit.\n")
        f.write("# source<TAB>text (\\t \\n \\\\ \\xHH escaped)<TAB>expected token ids ([UNK] removed)\n")
        for src, s in rows:
            ids = [i for i in tok.encode(s, add_special_tokens=False).ids if i != unk]
            esc = "".join("\\\\" if c == "\\" else "\\t" if c == "\t" else "\\n" if c == "\n" else
                          f"\\x{ord(c):02x}" if ord(c) < 0x20 or ord(c) == 0x7F else c for c in s)
            f.write(f"{src}\t{esc}\t{' '.join(map(str, ids))}\n")
    print(f"{a.out}: {len(rows)} sentences")


if __name__ == "__main__":
    main()
